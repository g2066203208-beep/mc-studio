import assert from 'node:assert/strict';
import {previewStress,STRESS_DEFAULTS} from '../kinetic-preview.mjs';
import {rotationRatio,evaluate,axisOf} from '../strict-core.mjs';
const b=(id,pos,axis='x',other={})=>({id,pos,axis,...other});
const motor=b('create:creative_motor',[0,1,0],'x',{facing:'east',rpm:16});
const shaft=b('create:shaft',[1,1,0]);
const press=b('create:mechanical_press',[2,1,0]);
const running=previewStress([motor,shaft,press]);
assert.equal(running.summary.running,3);
assert.equal(running.rpms['0,1,0'],16);
assert.equal(running.rpms['1,1,0'],16);
assert.equal(running.rpms['2,1,0'],16);
assert.equal(running.summary.capacity,16384*16,'1.21.1 official default creative motor capacity / RPM');
assert.equal(running.summary.impact,8*16,'mechanical press 8 SU per RPM');
assert.equal(running.summary.overstressed,0);
assert.equal(running.networks.filter(n=>n.status==='running').length,1);
const load=previewStress([motor,shaft,press],{capacityScale:.0001});
assert.equal(load.summary.overstressed,1,'user-adjusted SU budget must show overstress');
assert.equal(load.rpms['0,1,0'],0,'overloaded motor is stopped');
assert.equal(load.rpms['1,1,0'],0,'overloaded shaft is stopped');
assert.equal(load.rpms['2,1,0'],0,'overloaded mechanical press is stopped');
assert.ok(load.errors.some(e=>e.code==='OVERSTRESSED_PREVIEW'));
const noLoad=previewStress([motor,shaft]);
assert.equal(noLoad.summary.impact,0,'pure gearbox/shafts consume no stress');
assert.equal(noLoad.summary.overstressed,0);
assert.equal(STRESS_DEFAULTS['create:water_wheel'].capacity,32);
assert.equal(STRESS_DEFAULTS['create:large_water_wheel'].capacity,128);
const reverse=b('create:creative_motor',[0,1,0],'x',{facing:'west',rpm:16});
assert.equal(rotationRatio(reverse,shaft),0,'the motor shaft exists only in FACING direction');
assert.equal(evaluate([reverse,shaft]).rpms['1,1,0'],undefined,'misoriented motor must not power a shaft');
const clutch=b('create:clutch',[1,1,0],'x',{powered:false});
const beyond=b('create:shaft',[2,1,0]);
assert.equal(rotationRatio(motor,clutch),1);
assert.equal(previewStress([motor,clutch,beyond]).rpms['2,1,0'],16,'unpowered clutch connects');
clutch.powered=true;
assert.equal(rotationRatio(motor,clutch),0,'powered clutch disconnects from Create kinetic network');
assert.equal(previewStress([motor,clutch,beyond]).rpms['2,1,0'],undefined);
assert.equal(axisOf(motor),'x');
assert.equal(axisOf(b('create:mechanical_press',[2,1,0],'y',{facing:'east'})),'x',
 'Create press input axis must derive from horizontal facing');
assert.equal(rotationRatio(shaft,b('create:mechanical_mixer',[2,1,0],'x')),0,
 'original mixer HAS NO external shaft input; must not fake power');
const drill=b('create:mechanical_drill',[2,1,0],'x',{facing:'east'});
assert.equal(rotationRatio(shaft,drill),1,'Create drill receives input on back face');
const drillWrong=b('create:mechanical_drill',[2,1,0],'x',{facing:'west'});
assert.equal(rotationRatio(shaft,drillWrong),0,'Create drill refuses input on working head face');
const overloadSeparate=previewStress([motor,b('create:mechanical_press',[9,1,9])],{capacityScale:.0001});
assert.equal(overloadSeparate.summary.overstressed,0,'unconnected load cannot stall an unrelated motor');
assert.equal(overloadSeparate.rpms['0,1,0'],16);
assert.ok(overloadSeparate.warnings.some(e=>e.code==='NATIVE_GAME_REQUIRED'),'retain game authority warning');
console.log('PASS Create 1.21.1 motor one-sided output, clutch redstone disconnect, stress multipliers, SU overload and isolated networks');
