import assert from 'node:assert/strict';
import {rotationRatio,canPlace,evaluate,behavior} from '../strict-core.mjs';
const b=(id,x,y,z,axis='x',rpm)=>({id,pos:[x,y,z],axis,rpm});
const motor=b('create:creative_motor',0,1,0,'x',16),shaft=b('create:shaft',1,1,0,'x');
const cog=b('create:cogwheel',2,1,0,'x'),cog2=b('create:cogwheel',2,1,1,'x');
assert.equal(rotationRatio(motor,shaft),1);
assert.equal(rotationRatio(shaft,cog),1);
assert.equal(rotationRatio(cog,cog2),-1,'small cogwheels reverse');
assert.equal(rotationRatio(b('create:shaft',0,1,0,'x'),b('create:shaft',0,1,1,'x')),0,'shafts may not transmit sideways');
assert.equal(rotationRatio(b('create:cogwheel',0,1,0,'x'),b('create:cogwheel',1,1,0,'x')),1,'cogs share axial shafts');
assert.equal(rotationRatio(b('create:large_cogwheel',0,1,0,'y'),b('create:cogwheel',1,1,1,'y')),-2,'large->small diagonal ratio');
assert.equal(rotationRatio(b('create:cogwheel',1,1,1,'y'),b('create:large_cogwheel',0,1,0,'y')),-.5,'small->large diagonal ratio');
assert.equal(rotationRatio(b('create:large_cogwheel',0,1,0,'x'),b('create:large_cogwheel',1,2,0,'y')),1,'perpendicular large cog diagonal');
assert.equal(rotationRatio(b('create:large_cogwheel',0,1,0,'x'),b('create:large_cogwheel',1,1,0,'y')),0,'wrong separation must not mesh');
assert.equal(canPlace([],shaft).ok,true);
assert.equal(canPlace([shaft],shaft).ok,false,'no overlap');
assert.equal(canPlace([],b('create:shaft',0,2,0)).ok,false,'no air placement');
assert.equal(canPlace([b('minecraft:stone',0,1,0)],b('create:shaft',0,2,0)).ok,true,'neighbor support');
assert.equal(canPlace([],b('create:shaft',0,1.4,0)).ok,false,'block positions are integral');
const demo=evaluate([motor,shaft,cog,cog2]);
assert.equal(demo.summary.blocks,4);
assert.equal(demo.summary.links,3);
assert.equal(demo.summary.powered,4);
assert.equal(demo.rpms['2,1,1'],-16);
assert.ok(demo.warnings.some(e=>e.code==='NATIVE_GAME_REQUIRED'));
const unpowered=evaluate([b('simulated:swivel_bearing',0,1,0)]);
assert.equal(unpowered.summary.powered,0);
assert.ok(unpowered.warnings.some(e=>e.code==='SABLE_NOT_SIMULATED'));
assert.equal(behavior('simulated:physics_assembler').coverage,'requires-game');
const conflict=evaluate([b('create:creative_motor',0,1,0,'x',16),shaft,b('create:creative_motor',2,1,0,'x',-16)]);
assert.ok(conflict.errors.some(e=>e.code==='ROTATION_CONFLICT'),'opposed creative motors must be flagged');
console.log('PASS source-audited axial, gear, speed and no-fake-physics tests');